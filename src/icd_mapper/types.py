"""Shared Pydantic types used across loaders, clients, and pipelines.

Conventions:
- ICD-10-CM codes are stored *with* the period (e.g. "A00.1") in `code`,
  and *without* (e.g. "A001") in `code_nodot`. The CDC tabular files use the
  no-dot form; humans use the dotted form.
- ICD-11 Foundation entries are identified by their full IRI
  (e.g. "http://id.who.int/icd/entity/1435254666"). The trailing integer is
  the `entity_id`.
"""

from __future__ import annotations

from typing import Literal

from pydantic import BaseModel, Field, HttpUrl

# How a source code reaches ICD-11 (see docs/icd_mapping_3month_plan.md, "The pipeline").
#   foundation_is_mms           chosen Foundation entity is itself an MMS category: done
#   aggregated_postcoordinated  entity aggregates into another MMS entity; a validated
#                               cluster on the derived stem expresses it
#   aggregated_detail_lost      entity aggregates; no allowed axis expresses the difference
#   composed                    no Foundation entity; a cluster of stems/extensions
#                               composed and validated
#   none                        no ICD-11 representation (declined)
TargetType = Literal[
    "foundation_is_mms",
    "aggregated_postcoordinated",
    "aggregated_detail_lost",
    "composed",
    "none",
]


class ICD10CMCode(BaseModel):
    """A single ICD-10-CM code with title."""

    code: str = Field(description="Dotted form, e.g. 'A00.1'")
    code_nodot: str = Field(description="No-dot form, e.g. 'A001'")
    title: str = Field(description="Short description from the CDC codes file")
    chapter: int = Field(description="ICD-10-CM chapter number (1..22)")
    block: str | None = Field(default=None, description="Block prefix (e.g. 'A00-A09')")


class ICD11Entity(BaseModel):
    """A node in the ICD-11 Foundation (or MMS linearization)."""

    entity_id: str = Field(description="Trailing integer of the IRI, e.g. '1435254666'")
    iri: HttpUrl
    title: str
    definition: str | None = None
    synonyms: list[str] = Field(default_factory=list)
    inclusions: list[str] = Field(default_factory=list)
    exclusions: list[str] = Field(default_factory=list)
    parents: list[str] = Field(default_factory=list, description="Entity IDs of parent nodes")
    children: list[str] = Field(default_factory=list, description="Entity IDs of child nodes")
    code: str | None = Field(default=None, description="MMS code if this is a linearized entity")


class PostcoordinationAxis(BaseModel):
    """One postcoordination axis allowed on an MMS stem (from `postcoordinationScale`)."""

    axis_name: str = Field(description="Axis IRI, e.g. 'http://id.who.int/icd/schema/laterality'")
    required: bool = False
    allow_multiple: str = Field(default="NotAllowed", description="WHO value, e.g. 'NotAllowed'")
    scale_entities: list[str] = Field(
        default_factory=list, description="MMS URIs of the allowed values (often hierarchy roots)"
    )


class MmsDerivation(BaseModel):
    """Where a Foundation entity lands in MMS: itself, an ancestor, or a residual category."""

    foundation_uri: str
    mms_uri: str = Field(description="Linearization URI; may end in /unspecified or /other")
    code: str | None = Field(default=None, description="MMS code; None for blocks/chapters")
    title: str | None = None
    is_residual: bool = Field(
        default=False, description="True when mms_uri ends in /unspecified or /other"
    )
    axes: list[PostcoordinationAxis] = Field(default_factory=list)

    @property
    def requires_postcoordination(self) -> bool:
        return any(a.required for a in self.axes)


class ICD11Candidate(BaseModel):
    """One candidate ICD-11 Foundation entity proposed for a given ICD-10-CM code."""

    entity_id: str
    title: str
    mms_code: str | None = Field(default=None, description="Derived MMS code, shown as context")
    score: float = Field(ge=0.0, le=1.0, description="Retriever / verifier score")
    rationale: str | None = None


class MappingProposal(BaseModel):
    """Final mapping proposal from a pipeline run."""

    icd10cm_code: str = Field(description="Dotted ICD-10-CM code")
    candidates: list[ICD11Candidate] = Field(default_factory=list)
    chosen: ICD11Candidate | None = None
    confidence: float = Field(ge=0.0, le=1.0, default=0.0)
    rationale: str = ""
    # Which path produced the mapping (set by the pipeline, not the LLM).
    target_type: TargetType | None = None
    # Derived from `chosen` through the MMS linearization (never generated by the LLM).
    mms_uri: str | None = None
    mms_code: str | None = None
    is_residual: bool = False
    # Postcoordination: axis IRI -> extension code, and the validated cluster string,
    # e.g. "1A00&XN8P1" (expressing an aggregated Foundation entity) or a composed
    # "GB60.Z/GB61.4". `cluster_valid` is set from the ICD-API codeinfo check.
    extensions: dict[str, str] = Field(default_factory=dict)
    cluster: str | None = None
    cluster_valid: bool | None = None
    # Who proposed the cluster: "claude", "codefusion_default", "codefusion_free",
    # or "codefusion_default+claude" when Claude accepted/edited a CodeFusion proposal.
    cluster_source: str | None = None
    # Cost accounting
    input_tokens: int = 0
    output_tokens: int = 0
    cost_usd: float = 0.0


def _two_digit_prefix(code: str) -> int:
    """Numeric value of characters 2-3, tolerating a letter in position 3.

    'D49' -> 49, 'D3A' -> 30 (D3A, neuroendocrine tumors, sits in D00-D49), 'H60' -> 60.
    """
    if len(code) < 2 or not code[1].isdigit():
        raise ValueError(f"Cannot parse chapter for {code!r}")
    second = int(code[2]) if len(code) > 2 and code[2].isdigit() else 0
    return int(code[1]) * 10 + second


def chapter_for_icd10cm_code(code: str) -> int:
    """Return the ICD-10-CM chapter number (1..22) for a code's letter prefix.

    Based on the 2026 ICD-10-CM chapter ranges. Z codes → Ch. 21,
    U codes → Ch. 22 (special purposes).
    """
    if not code:
        raise ValueError("Empty code")
    first = code[0].upper()
    if first == "A" or first == "B":
        return 1
    if first == "C":
        return 2
    if first == "D":
        # D00-D49 → Ch. 2 (neoplasms, including D3A), D50-D89 → Ch. 3 (blood)
        return 2 if _two_digit_prefix(code) <= 49 else 3
    if first == "E":
        return 4
    if first == "F":
        return 5
    if first == "G":
        return 6
    if first == "H":
        return 7 if _two_digit_prefix(code) <= 59 else 8  # H00-H59 eye, H60-H95 ear
    if first == "I":
        return 9
    if first == "J":
        return 10
    if first == "K":
        return 11
    if first == "L":
        return 12
    if first == "M":
        return 13
    if first == "N":
        return 14
    if first == "O":
        return 15
    if first == "P":
        return 16
    if first == "Q":
        return 17
    if first == "R":
        return 18
    if first in ("S", "T"):
        return 19
    if first in ("V", "W", "X", "Y"):
        return 20
    if first == "Z":
        return 21
    if first == "U":
        return 22
    raise ValueError(f"Unknown ICD-10-CM letter prefix for code {code!r}")
